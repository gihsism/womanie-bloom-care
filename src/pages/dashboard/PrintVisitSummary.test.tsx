import { describe, it, expect } from 'vitest';
import { render, screen } from '@testing-library/react';
import { VisitSummarySheet, type VisitSummaryData } from './PrintVisitSummary';

const NOW = new Date(2026, 10, 25, 10, 0);
const data: VisitSummaryData = {
  name: 'Anna Muster',
  stage: 'menstrual-cycle',
  dueDate: null,
  periods: [
    { period_start_date: '2026-11-20', period_end_date: null },
    { period_start_date: '2026-10-23', period_end_date: '2026-10-27' },
  ],
  medicines: [{ name: 'Iron', dose: '50 mg', times_per_day: 1 }],
  signals: [{ signal_date: '2026-11-24', symptoms: ['cramps'], mood: ['calm'] }],
  questionRows: [{ questions: [{ id: 'a', text: 'Should I check my ferritin?', asked: false }] }],
  results: [{ title: 'Ferritin', value: '12', unit: 'ng/mL', reference_range: '15-150', status: 'abnormal', date_recorded: '2026-10-01', data_type: 'lab_result' }],
  documents: [{ file_name: 'secret-scan.pdf', ai_suggested_name: 'Pelvic ultrasound', uploaded_at: '2026-10-02' }],
};

describe('VisitSummarySheet', () => {
  it('prints every chosen section with the footer', () => {
    const { container } = render(
      <VisitSummarySheet data={data} now={NOW} sections={['stage', 'cycles', 'medicines', 'symptoms', 'questions', 'results', 'documents']} />,
    );
    expect(screen.getByText('Anna Muster')).toBeInTheDocument();
    expect(screen.getByText(/^Cycle day 6 /)).toBeInTheDocument();
    expect(screen.getByText('28 days')).toBeInTheDocument();
    expect(screen.getByText('Iron 50 mg, 1× daily')).toBeInTheDocument();
    expect(screen.getByText('Symptoms: Cramps on 1 day.')).toBeInTheDocument();
    expect(screen.getByText('Should I check my ferritin?')).toBeInTheDocument();
    expect(screen.getByText('Outside range')).toBeInTheDocument();
    expect(screen.getByText('Pelvic ultrasound')).toBeInTheDocument();
    expect(container.textContent).toMatch(/Generated by Womanie on .*Not a diagnosis/);
  });

  it('leaves out what she unticked (privacy)', () => {
    const { container } = render(<VisitSummarySheet data={data} now={NOW} sections={['stage']} />);
    expect(container.querySelectorAll('[data-section]')).toHaveLength(1);
    expect(container.textContent).not.toContain('Pelvic ultrasound');
    expect(container.textContent).not.toContain('Iron');
    expect(container.textContent).not.toContain('ferritin');
  });

  it('empty sections say so calmly', () => {
    const empty: VisitSummaryData = { ...data, medicines: [], signals: [], questionRows: [] };
    render(<VisitSummarySheet data={empty} now={NOW} sections={['medicines', 'symptoms', 'questions']} />);
    expect(screen.getByText('None recorded.')).toBeInTheDocument();
    expect(screen.getByText('Nothing logged in the last 30 days.')).toBeInTheDocument();
    expect(screen.getByText('No open questions saved.')).toBeInTheDocument();
  });
});
