import { describe, it, expect } from 'vitest';
import { render, screen } from '@testing-library/react';
import { VisitPrepSheet, type VisitPrepData } from './PrintVisitPrep';

const NOW = new Date(2026, 10, 25, 10, 0);
const base: VisitPrepData = {
  name: 'Anna Muster',
  visit: { scheduled_at: '2026-12-02T09:30:00', doctor: 'Dr. Meier' },
  stage: 'menstrual-cycle',
  dueDate: null,
  periods: [{ period_start_date: '2026-11-20', period_end_date: null }],
  medicines: [{ name: 'Iron', dose: '50 mg', times_per_day: 1, active: true }],
  visitQuestions: { questions: [{ id: 'a', text: 'Should I keep taking iron?', asked: false }, { id: 'b', text: 'Old one', asked: true }] },
  unscheduledQuestions: { questions: [{ id: 'c', text: 'Unscheduled question', asked: false }] },
  results: [
    { title: 'Ferritin', value: '12', unit: 'ng/mL', reference_range: '15-150', status: 'abnormal', date_recorded: '2026-10-01', data_type: 'lab_result', document_id: null },
    { title: 'Ferritin', value: '30', unit: 'ng/mL', reference_range: '15-150', status: 'normal', date_recorded: '2026-04-01', data_type: 'lab_result', document_id: null },
    { title: 'TSH', value: '2.0', unit: 'mIU/L', reference_range: null, status: 'normal', date_recorded: '2026-10-01', data_type: 'lab_result', document_id: null },
  ],
};

describe('VisitPrepSheet', () => {
  it('prints the visit, the stage line, open questions, medicines and results to bring up', () => {
    const { container } = render(<VisitPrepSheet data={base} now={NOW} />);
    expect(screen.getByText('Anna Muster')).toBeInTheDocument();
    expect(container.textContent).toMatch(/Visit on .*2026 at .* with Dr\. Meier/);
    expect(screen.getByText(/^Cycle day 6 /)).toBeInTheDocument();
    expect(screen.getByText('Should I keep taking iron?')).toBeInTheDocument();
    expect(container.textContent).not.toContain('Old one');
    expect(container.textContent).not.toContain('Unscheduled question');
    expect(screen.getByText('Iron 50 mg, 1× daily')).toBeInTheDocument();
    expect(screen.getByText('Marked outside range; was 30 ng/mL (within range) on 1 Apr 2026')).toBeInTheDocument();
    // A within-range, unchanged TSH is not on the sheet.
    expect(container.textContent).not.toContain('TSH');
    expect(container.textContent).toMatch(/Generated by Womanie on .*Not a diagnosis/);
  });

  it('falls back to questions saved before the visit was booked, and says so', () => {
    render(<VisitPrepSheet data={{ ...base, visitQuestions: null }} now={NOW} />);
    expect(screen.getByText('Unscheduled question')).toBeInTheDocument();
    expect(screen.getByText('Saved before this visit was booked.')).toBeInTheDocument();
  });

  it('says plainly when there is nothing to list', () => {
    render(<VisitPrepSheet data={{ ...base, visitQuestions: null, unscheduledQuestions: null, medicines: [], results: [] }} now={NOW} />);
    expect(screen.getByText('No open questions saved for this visit.')).toBeInTheDocument();
    expect(screen.getByText('None recorded.')).toBeInTheDocument();
    expect(screen.getByText('No results outside the range or changed since the previous test.')).toBeInTheDocument();
  });

  it('shows the pregnancy week line and the last-checked note for TSH in pregnancy', () => {
    const data: VisitPrepData = {
      ...base, stage: 'pregnancy', dueDate: '2027-04-01', periods: [],
      results: [{ title: 'TSH', value: '2.0', unit: 'mIU/L', reference_range: null, status: 'normal', date_recorded: '2026-03-01', data_type: 'lab_result', document_id: null }],
    };
    const { container } = render(<VisitPrepSheet data={data} now={NOW} />);
    expect(screen.getByText(/^Pregnancy week /)).toBeInTheDocument();
    expect(container.textContent).toContain('TSH: last checked 8 months ago (1 Mar 2026). That was before this pregnancy.');
  });

  it('menopause: prints the 4-week symptom diary with a neutral sentence', () => {
    const data: VisitPrepData = {
      ...base, stage: 'menopause', periods: [],
      signals: [
        { signal_date: '2026-11-24', notes: 'Hot flashes: 5. Sleep quality: 2/5', mood: ['anxious'] },
        { signal_date: '2026-11-10', symptoms: ['Hot flashes'] },
      ],
    };
    const { container } = render(<VisitPrepSheet data={data} now={NOW} />);
    const section = container.querySelector('[data-section="symptom-diary"]')!;
    expect(section.textContent).toContain('Symptom diary, last 4 weeks');
    expect(section.textContent).toContain('Logged on 2 of the last 28 days. In that time: hot flushes on 2 days (5 hot flushes counted), poor sleep on 1 night and low mood on 1 day.');
    expect(section.querySelectorAll('thead th')).toHaveLength(5);
    expect(screen.getByText('Hot flushes counted')).toBeInTheDocument();
    expect(container.querySelector('[data-section="ttc-cycles"]')).toBeNull();
  });

  it('not in a menopause stage or TTC: neither summary is on the sheet', () => {
    const { container } = render(<VisitPrepSheet data={{ ...base, signals: [{ signal_date: '2026-11-24', notes: 'Hot flashes: 5' }] }} now={NOW} />);
    expect(container.querySelector('[data-section="symptom-diary"]')).toBeNull();
    expect(container.querySelector('[data-section="ttc-cycles"]')).toBeNull();
  });

  it('trying to conceive: prints cycle and period lengths with the logged ovulation tests', () => {
    const data: VisitPrepData = {
      ...base, stage: 'conception',
      periods: [
        { period_start_date: '2026-11-20', period_end_date: '2026-11-24' },
        { period_start_date: '2026-10-22', period_end_date: '2026-10-26' },
      ],
      signals: [{ signal_date: '2026-11-04', notes: 'LH test: peak' }],
    };
    const { container } = render(<VisitPrepSheet data={data} now={NOW} />);
    const section = container.querySelector('[data-section="ttc-cycles"]')!;
    expect(section.textContent).toContain('Cycle length 29 days over 1 cycle. Period length 5 days. Ovulation tests logged in 1 of 2 cycles; a positive or peak result in 1.');
    expect(section.textContent).toContain('1 test; day 14 peak');
    expect(section.textContent).toContain('current');
  });
});
